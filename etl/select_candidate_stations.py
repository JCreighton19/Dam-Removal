"""
Pass 1 of 2 for building the dam-station analysis set: select candidate WQP
stations using a configurable geographic search distance around relevant
dams.

This is the sole, canonical generator of
`data/raw/wqp/results/pilot_station_selection.csv`. Nothing else should
write to that path -- it was previously regenerated by two different,
conflicting notebook cells (a random per-HUC8 sample, and a dam-linked
subset computed *after* network linking already existed), which is the
problem this script replaces.

Candidate selection here is purely geographic (nearest dam, straight-line
distance) and runs *before* NHDPlus download/extraction/snapping, so it
has no dependency on network connectivity. Pass 2 -- `snap_features.py`
followed by `link_dams_stations.py` -- takes these candidates and produces
the actual confirmed upstream/downstream/same-reach relationships
(`data/processed/dam_station_links_{huc8}.csv`), which remains a separate
output.

The distance threshold (`candidate_distance_km` in the case-study config)
is explicitly a provisional discovery parameter, not a scientifically
validated cutoff. This script also reports candidate counts at several
other thresholds (`candidate_distance_sensitivity_km`) so the choice can be
sanity-checked.
"""

from __future__ import annotations

import argparse
import sys
from datetime import datetime
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import geopandas as gpd
import pandas as pd

from etl.common.config import load_config
from etl.common.dams import load_dams
from etl.common.wbd import clip_to_watersheds, load_huc8_watersheds

DEFAULT_STATION_TYPES = ["Stream", "River/Stream"]
DEFAULT_SENSITIVITY_KM = [1, 2, 5, 10, 25, 50]

CANDIDATE_COLUMNS = {
    "MonitoringLocationIdentifier",
    "source_huc8",
    "nearest_dam_id",
    "distance_to_nearest_dam_km",
}


def load_scope_stations(station_dir, huc8s, station_types):
    """Load raw downloaded WQP station files for this case study's HUC8s.

    Each file is the per-HUC8 output of download_wqp_stations.py, named
    "<huc8>.csv". Loading by exact filename (rather than globbing every
    file in the directory) means a case study's candidate set is only ever
    built from the HUC8s it actually declares.
    """
    station_dir = Path(station_dir)
    frames = []
    missing = []

    for huc8 in huc8s:
        path = station_dir / f"{huc8}.csv"
        if not path.exists():
            missing.append(str(path))
            continue
        df = pd.read_csv(path, low_memory=False)
        df["source_huc8"] = huc8
        frames.append(df)

    if missing:
        raise FileNotFoundError(
            "Missing downloaded WQP station file(s) for this case study's "
            f"HUC8 scope: {missing}. Run download_wqp_stations.py first."
        )

    stations = pd.concat(frames, ignore_index=True)

    stations = stations[
        stations["MonitoringLocationTypeName"].isin(station_types)
    ].copy()

    for col in ["LatitudeMeasure", "LongitudeMeasure"]:
        stations[col] = pd.to_numeric(stations[col], errors="coerce")

    stations = stations.dropna(subset=["LatitudeMeasure", "LongitudeMeasure"])
    stations = stations[
        stations["LatitudeMeasure"].between(-90, 90)
        & stations["LongitudeMeasure"].between(-180, 180)
    ].copy()
    stations = stations.drop_duplicates(subset="MonitoringLocationIdentifier")

    return gpd.GeoDataFrame(
        stations,
        geometry=gpd.points_from_xy(
            stations["LongitudeMeasure"], stations["LatitudeMeasure"]
        ),
        crs="EPSG:4326",
    )


def compute_nearest_dam(stations, dams):
    """For each station, find the nearest dam (AR_ID) and distance in km.

    Both inputs are reprojected to a local projected CRS (estimated from
    their combined extent) so distance is computed in meters, not degrees.
    """
    if dams.empty:
        raise ValueError("No dams were provided to compute distances against.")

    combined = gpd.GeoDataFrame(
        geometry=pd.concat([stations.geometry, dams.geometry], ignore_index=True),
        crs=stations.crs,
    )
    metric_crs = combined.estimate_utm_crs()

    stations_m = stations.to_crs(metric_crs)
    dams_m = dams[["AR_ID", "geometry"]].to_crs(metric_crs)

    joined = gpd.sjoin_nearest(
        stations_m,
        dams_m,
        how="left",
        distance_col="distance_to_nearest_dam_m",
    ).drop(columns="index_right", errors="ignore")

    joined = joined.rename(columns={"AR_ID": "nearest_dam_id"})
    joined["distance_to_nearest_dam_km"] = (
        joined["distance_to_nearest_dam_m"] / 1000.0
    )

    return joined.to_crs(stations.crs)


def build_sensitivity_report(joined, threshold_km, sensitivity_km):
    thresholds = sorted(set(sensitivity_km) | {threshold_km})
    rows = []

    for distance in thresholds:
        subset = joined[joined["distance_to_nearest_dam_km"] <= distance]
        rows.append({
            "distance_km": distance,
            "candidate_station_count": subset["MonitoringLocationIdentifier"].nunique(),
            "dams_with_a_candidate": subset["nearest_dam_id"].nunique(),
            "is_selected_threshold": distance == threshold_km,
        })

    return pd.DataFrame(rows)


def validate_candidates(candidates, threshold_km):
    """Validate a completed candidate table before it is allowed to be written.

    This is the guard against overwriting the production file with a
    broken or empty result -- failures here must not touch disk.
    """
    missing_cols = CANDIDATE_COLUMNS - set(candidates.columns)
    if missing_cols:
        raise ValueError(
            f"Candidate table is missing expected columns: {sorted(missing_cols)}"
        )

    if candidates.empty:
        raise ValueError(
            f"No candidate stations found within {threshold_km} km of an "
            "in-scope dam. Refusing to overwrite the existing candidate "
            "file with an empty result."
        )

    if candidates["MonitoringLocationIdentifier"].isna().any():
        raise ValueError(
            "Candidate table has rows with a missing MonitoringLocationIdentifier."
        )

    if (candidates["distance_to_nearest_dam_km"] < 0).any():
        raise ValueError(
            "Candidate table has negative distances; something is wrong upstream."
        )


def _write_failure_manifest(manifest_path, cfg_name, error):
    manifest_path.parent.mkdir(parents=True, exist_ok=True)
    pd.DataFrame([{
        "status": "failed",
        "case_study": cfg_name,
        "candidate_distance_km": "",
        "dams_in_scope": "",
        "stations_considered": "",
        "candidate_station_count": "",
        "generated_at": datetime.now().isoformat(timespec="seconds"),
        "error_message": str(error),
    }]).to_csv(manifest_path, index=False)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--case-study",
        default="pilot_19020401",
        help="Name of a config file under config/ (without the .yaml extension).",
    )
    args = parser.parse_args()

    cfg = load_config(args.case_study)

    results_dir = cfg.project_root / "data" / "raw" / "wqp" / "results"
    output_path = results_dir / "pilot_station_selection.csv"
    sensitivity_path = results_dir / "pilot_station_selection_sensitivity.csv"
    manifest_path = results_dir / "pilot_station_selection_manifest.csv"

    try:
        print(f"Case study: {cfg.name}")
        print(f"HUC8 scope: {cfg.huc8s}")

        watersheds = load_huc8_watersheds(cfg.path("wbd_source"), cfg.huc8s)
        dams = load_dams(cfg.path("dam_source"))
        dams_in_scope = clip_to_watersheds(dams, watersheds)

        if dams_in_scope.empty:
            raise ValueError(
                "No dams found within this case study's watershed(s); "
                "check dam_source/huc8s in the config."
            )

        print(f"Dams in scope: {dams_in_scope['AR_ID'].nunique():,}")

        station_dir = cfg.project_root / "data" / "raw" / "wqp" / "stations"
        station_types = cfg.get("station_types", DEFAULT_STATION_TYPES)
        stations = load_scope_stations(station_dir, cfg.huc8s, station_types)

        print(f"Candidate surface-water stations considered: {len(stations):,}")

        joined = compute_nearest_dam(stations, dams_in_scope)

        threshold_km = float(cfg.get("candidate_distance_km", 5))
        sensitivity_km = cfg.get(
            "candidate_distance_sensitivity_km", DEFAULT_SENSITIVITY_KM
        )

        sensitivity = build_sensitivity_report(joined, threshold_km, sensitivity_km)
        print("\nCandidate count sensitivity to distance threshold:")
        print(sensitivity.to_string(index=False))

        candidates = joined[
            joined["distance_to_nearest_dam_km"] <= threshold_km
        ].copy()

        validate_candidates(candidates, threshold_km)

        # Write to temp files first; only replace the production outputs
        # once everything above has validated successfully.
        results_dir.mkdir(parents=True, exist_ok=True)

        tmp_output = output_path.with_suffix(".tmp.csv")
        candidates.drop(columns="geometry").to_csv(tmp_output, index=False)
        tmp_output.replace(output_path)

        sensitivity.to_csv(sensitivity_path, index=False)

        manifest_row = {
            "status": "ok",
            "case_study": cfg.name,
            "candidate_distance_km": threshold_km,
            "dams_in_scope": int(dams_in_scope["AR_ID"].nunique()),
            "stations_considered": int(len(stations)),
            "candidate_station_count": int(
                candidates["MonitoringLocationIdentifier"].nunique()
            ),
            "generated_at": datetime.now().isoformat(timespec="seconds"),
            "error_message": "",
        }
        pd.DataFrame([manifest_row]).to_csv(manifest_path, index=False)

        print(
            f"\nSelected {manifest_row['candidate_station_count']:,} candidate "
            f"stations within {threshold_km} km of a dam."
        )
        print(f"Saved: {output_path}")
        print(f"Sensitivity report: {sensitivity_path}")
        print(f"Manifest: {manifest_path}")

    except Exception as exc:
        _write_failure_manifest(manifest_path, args.case_study, exc)
        print(f"FAILED: {exc}", file=sys.stderr)
        raise


if __name__ == "__main__":
    main()
