"""
Create a new case-study config scoped to N randomly sampled dam removals.

Samples N dams (default 5) from the dam-removal source CSV, resolves each
to its containing HUC8 watershed via the national WBD, and writes a new
config/<name>.yaml with those HUC8s as the scope -- reusing the exact same
huc8s-based scoping mechanism every other script already reads. Nothing
downstream needs to change to support this; it's just a different
config/case_study.env target.

Important caveat: scope is still by WATERSHED, not by these exact N dams.
If a sampled watershed happens to contain other dam removals too, those
will also be swept in once snap_features.py clips dams to the watershed
polygon -- there is no "only these exact dam IDs" filter anywhere
downstream of this script. The sampled AR_IDs are recorded in the
generated config's `sampled_dams` field for reference, but nothing reads
that field back to filter anything.

Also note: with N dams spanning multiple HUC8s, every per-watershed
script (snap_features.py, link_dams_stations.py, report_pilot_eligibility.py)
now needs to process each of those HUC8s -- which they do automatically
(looping over cfg.huc8s) as long as you don't pass an explicit --huc8.
"""

from __future__ import annotations

import argparse
import random
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import yaml

from etl.common.config import load_config
from etl.common.dams import load_dams
from etl.common.wbd import resolve_huc8_for_points


def sample_dams(dams, n_dams, seed):
    rng = random.Random(seed)
    n_dams = min(n_dams, len(dams))
    indices = rng.sample(range(len(dams)), k=n_dams)
    return dams.iloc[sorted(indices)].reset_index(drop=True)


def build_config_dict(case_study_name, base_cfg, resolved, seed, n_dams, base_case_study):
    name_col = "Dam_Name" if "Dam_Name" in resolved.columns else None
    huc8s = sorted(resolved["resolved_huc8"].unique())

    sampled_dams = [
        {
            "AR_ID": str(row["AR_ID"]),
            "huc8": row["resolved_huc8"],
            "name": str(row[name_col]) if name_col else "",
        }
        for _, row in resolved.iterrows()
    ]

    return {
        "case_study": case_study_name,
        "huc8s": huc8s,
        "dam_source": base_cfg.raw["dam_source"],
        "wbd_source": base_cfg.raw["wbd_source"],
        "station_types": base_cfg.get("station_types", []),
        "wq_window": base_cfg.get("wq_window", {}),
        "wq_characteristics": base_cfg.get("wq_characteristics", []),
        "sampled_dams": sampled_dams,
        "sampling": {
            "seed": seed,
            "n_dams_requested": n_dams,
            "n_dams_resolved": len(resolved),
            "source_case_study": base_case_study,
        },
    }


def main():
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument(
        "--base-case-study",
        default="pilot_19020401",
        help="Existing config to copy dam_source/wbd_source/station_types/"
        "wq_window/wq_characteristics from.",
    )
    parser.add_argument("--n-dams", type=int, default=5)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument(
        "--name",
        default=None,
        help="Output case-study name; defaults to pilot_random<n>_seed<seed>.",
    )
    args = parser.parse_args()

    base_cfg = load_config(args.base_case_study)
    case_study_name = args.name or f"pilot_random{args.n_dams}_seed{args.seed}"

    print(f"Loading dams from: {base_cfg.path('dam_source')}")
    dams = load_dams(base_cfg.path("dam_source"))
    print(f"Dams with valid coordinates: {len(dams):,}")

    sampled = sample_dams(dams, args.n_dams, args.seed)
    print(f"Sampled {len(sampled)} dams (seed={args.seed})")

    resolved = resolve_huc8_for_points(sampled, base_cfg.path("wbd_source"))

    unresolved = resolved[resolved["resolved_huc8"].isna()]
    if not unresolved.empty:
        raise ValueError(
            f"{len(unresolved)} sampled dam(s) could not be resolved to a "
            f"HUC8 watershed (outside WBD coverage?): "
            f"{unresolved['AR_ID'].tolist()}"
        )

    config_dict = build_config_dict(
        case_study_name, base_cfg, resolved, args.seed, args.n_dams, args.base_case_study
    )

    output_path = base_cfg.project_root / "config" / f"{case_study_name}.yaml"
    header = (
        f"# Auto-generated by sample_random_pilot.py "
        f"--n-dams {args.n_dams} --seed {args.seed} --base-case-study {args.base_case_study}\n"
        "# Scope is by HUC8 watershed, not by the exact dam IDs below -- see\n"
        "# this script's module docstring.\n\n"
    )
    output_path.write_text(header + yaml.safe_dump(config_dict, sort_keys=False))

    name_col = "Dam_Name" if "Dam_Name" in resolved.columns else None
    print(f"\nSampled dams -> HUC8:")
    for _, row in resolved.iterrows():
        label = row[name_col] if name_col else ""
        print(f"  AR_ID={row['AR_ID']}  HUC8={row['resolved_huc8']}  {label}")

    print(f"\nUnique HUC8 watersheds: {len(config_dict['huc8s'])}")
    print(f"Wrote: {output_path}")
    print(
        f"\nTo use it, set in data/slurm/case_study.env:\n"
        f"  export DAM_REMOVAL_CASE_STUDY={case_study_name}"
    )


if __name__ == "__main__":
    main()
