"""Shared helpers for loading the dam-removal source dataset."""

from __future__ import annotations

import geopandas as gpd
import pandas as pd

from .io import find_column, require_file


def load_dams(dam_path):
    """Load the dam-removal CSV as a point GeoDataFrame in EPSG:4326."""
    dam_path = require_file(dam_path, "Dam removal CSV")
    dams = pd.read_csv(dam_path, low_memory=False)

    lat_col = find_column(dams.columns, "Latitude")
    lon_col = find_column(dams.columns, "Longitude")

    if lat_col is None or lon_col is None:
        raise ValueError(
            "Could not find dam coordinate columns. "
            f"Available columns: {dams.columns.tolist()}"
        )

    dams[lat_col] = pd.to_numeric(dams[lat_col], errors="coerce")
    dams[lon_col] = pd.to_numeric(dams[lon_col], errors="coerce")
    dams = dams.dropna(subset=[lat_col, lon_col]).copy()

    dams = dams[
        dams[lat_col].between(-90, 90) & dams[lon_col].between(-180, 180)
    ].copy()

    return gpd.GeoDataFrame(
        dams,
        geometry=gpd.points_from_xy(dams[lon_col], dams[lat_col]),
        crs="EPSG:4326",
    )


def filter_to_sampled_dams(dams, cfg):
    """Keep only the dams listed in the config's `sampled_dams`, if any.

    Configs generated by sample_random_pilot.py scope the pipeline to whole
    HUC8s but record the sampled dams; without this filter every dam removal
    in those HUC8s flows through snapping, linking and the WQP download.
    Set `restrict_to_sampled_dams: false` in the config to keep every dam.
    Configs without `sampled_dams` are returned unchanged.
    """
    sampled = cfg.get("sampled_dams") or []
    if not sampled or not cfg.get("restrict_to_sampled_dams", True):
        return dams

    sampled_ids = {str(dam["AR_ID"]) for dam in sampled}
    filtered = dams[dams["AR_ID"].astype(str).isin(sampled_ids)].copy()

    missing = sampled_ids - set(filtered["AR_ID"].astype(str))
    if missing:
        raise ValueError(
            f"Sampled dam(s) {sorted(missing)} from the config were not found "
            "in the dam source (or lack valid coordinates)."
        )

    return filtered
